/**
 * Brand marks for the services an eprint links out to.
 *
 * @remarks
 * Kept as icon components with the same shape as a Lucide icon, so a service's
 * own mark can be passed anywhere the shared card takes an icon. A recognised
 * mark is the fastest thing on a card to read, and the difference between a
 * generic document glyph and Leaflet's is the difference between a card a
 * reader scans and one they have to parse.
 *
 * Each mark below was taken from the service's own published asset -- an
 * `icon.svg`, a logo in its application bundle, or the mark inlined in its
 * homepage -- and reproduced as-is. Nothing here is drawn by hand: a mark that
 * merely resembles a service\'s is worse than a generic glyph, because it
 * misrepresents them.
 *
 * Leaflet's own `icon.svg` is a PNG in an SVG wrapper, but the project keeps a
 * proper set of ecosystem marks at `public/logos/` in hyperlink-academy/leaflet,
 * which is where its mark and Tangled's come from.
 *
 * Smoke Signal publishes no vector anywhere I could find and so is not here; it
 * keeps a Lucide glyph, and its cards stay labelled with the service name.
 *
 * @packageDocumentation
 */

